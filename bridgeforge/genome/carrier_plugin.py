"""94.G2 slice 7: the plugin a star-system gene's carrier gets, so the carrier makes the call the donor's plugin made.

A star-system gene's registration is an element, not a member (genome/campaign.py): the donor's plugin also holds other
features, so it is not carried. The carrier gets its own small `BaseModPlugin` instead, `bfgene.CarrierPlugin`, whose hook
makes the recorded call: `new <generator>().<method>(Global.getSector())` in the hook the donor's call is reached from.

The generator's class and method names come from a mod's bytecode, so they are untrusted: each must be a plain Java name
(identifiers joined by dots) before it is written into source, or the plugin is refused. Compiled with the house javac
settings (`run_javac`: `--release 17 -proc:none -encoding UTF-8`) against the core's `starfarer.api.jar` and the carrier's
own jars; a compile error is a refusal that names javac's first error, never a guess. The jar is written with zipfile, as
`patch-jar-class` writes its jars (the jar that loaded no class in 2026-10 was .NET ZipArchive's Update mode).
"""
from __future__ import annotations

import hashlib
import os
import re
import tempfile
import zipfile
from pathlib import Path

from bridgeforge.safeio import atomic_write_text

PLUGIN_CLASS = "bfgene.CarrierPlugin"
PLUGIN_JAR = "jars/bfgene_carrier.jar"
# The hooks a generated plugin may override, in lifecycle order, with their Java signatures (BaseModPlugin on RC7, javap
# 2026-11-19).
HOOK_SIGNATURES = {
    "onNewGame": "public void onNewGame()",
    "onNewGameAfterProcGen": "public void onNewGameAfterProcGen()",
    "onNewGameAfterEconomyLoad": "public void onNewGameAfterEconomyLoad()",
    "onNewGameAfterTimePass": "public void onNewGameAfterTimePass()",
    "onGameLoad": "public void onGameLoad(boolean newGame)",
}
_JAVA_NAME = re.compile(r"[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*\Z")
_JAVA_IDENT = re.compile(r"[A-Za-z_$][\w$]*\Z")


class CarrierPluginRefused(ValueError):
    """The carrier cannot be given a plugin that makes the recorded call."""


def call_of(registrations: list[dict]) -> tuple[str, str, str]:
    """(generator class, method, hook) the recorded registrations agree on; refused when they do not, or a name is unsafe."""
    calls = set()
    for element in registrations:
        generator, _, called = element.get("statement", "").partition(":")
        methods = [name.strip() for name in called.split(",") if name.strip() and name.strip() != "<init>"]
        # The first hook in lifecycle order that has a generated form (`hooks` is sorted by name: onGameLoad came first
        # and would have generated the system on every load; review 2026-11-20).
        hooks = [hook for hook in HOOK_SIGNATURES if hook in (element.get("hooks") or [])]
        if len(methods) == 1 and hooks:
            calls.add((generator.strip(), methods[0], hooks[0]))
    if len(calls) != 1:
        raise CarrierPluginRefused(f"the registrations name {len(calls)} distinct (class, method, hook) calls with a generated "
                                   f"hook ({', '.join(HOOK_SIGNATURES)}); a generated plugin makes exactly one")
    generator, method, hook = calls.pop()
    if not _JAVA_NAME.match(generator) or not _JAVA_IDENT.match(method):
        raise CarrierPluginRefused(f"{generator!r}.{method!r} is not a plain Java name: not written into source")
    if "$" in generator or "." not in generator:
        raise CarrierPluginRefused(f"{generator} is a nested class or in the default package: a plugin in package bfgene "
                                   "cannot name it in source")
    if hook not in HOOK_SIGNATURES:
        raise CarrierPluginRefused(f"hook {hook!r} has no generated form (known: {', '.join(HOOK_SIGNATURES)})")
    return generator, method, hook


def source_text(generator: str, method: str, hook: str) -> str:
    return (f"package bfgene;\n\nimport com.fs.starfarer.api.BaseModPlugin;\nimport com.fs.starfarer.api.Global;\n\n"
            f"/** Generated by BridgeForge's gene proof (94.G2): makes the call the donor's plugin made. */\n"
            f"public class CarrierPlugin extends BaseModPlugin {{\n    @Override\n    {HOOK_SIGNATURES[hook]} {{\n"
            f"        new {generator}().{method}(Global.getSector());\n    }}\n}}\n")


def build(dest: Path, registrations: list[dict], vanilla_core: Path | None, work: Path) -> dict:
    """Write `bfgene.CarrierPlugin` into the carrier `dest` (its jar `PLUGIN_JAR`); the source and javac's output go to `work`.
    Returns {"class", "jar", "statement", "source_sha256", "class_sha256"}."""
    from bridgeforge.bytecode.java_toolchain import find_jdk, run_javac

    generator, method, hook = call_of(registrations)
    api = Path(vanilla_core) / "starfarer.api.jar" if vanilla_core else None
    if api is None or not api.is_file():
        raise CarrierPluginRefused("compiling the carrier's plugin needs the core's starfarer.api.jar (--vanilla-core)")
    jdk = find_jdk()
    if jdk is None:
        raise CarrierPluginRefused("no JDK found to compile the carrier's plugin")
    text = source_text(generator, method, hook)
    source = Path(work) / "carrier-plugin" / "bfgene" / "CarrierPlugin.java"
    source.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(source, text, newline="")  # "" writes the text as is: the bytes on disk are what source_sha256 hashes
    jars = sorted(str(path) for path in Path(dest).rglob("*.jar"))
    with tempfile.TemporaryDirectory(prefix="bf-carrier-plugin-") as classes:
        try:
            run = run_javac(jdk.javac, os.pathsep.join([str(api), *jars]), [source], Path(classes))
        except OSError as error:
            raise CarrierPluginRefused(f"javac could not be started: {error}") from error
        if run.returncode != 0:
            first = (run.errors[0].get("message") if run.errors else None) or run.stderr.strip()[:300]
            raise CarrierPluginRefused(f"javac refused the carrier's plugin: {first}")
        compiled = Path(classes) / "bfgene" / "CarrierPlugin.class"
        data = compiled.read_bytes()
    (Path(dest) / PLUGIN_JAR).parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(Path(dest) / PLUGIN_JAR, "w", zipfile.ZIP_DEFLATED) as jar:
        jar.writestr("bfgene/CarrierPlugin.class", data)
    return {"class": PLUGIN_CLASS, "jar": PLUGIN_JAR, "hook": hook, "statement": f"new {generator}().{method}(Global.getSector())",
            "source_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(), "class_sha256": hashlib.sha256(data).hexdigest()}


__all__ = ["CarrierPluginRefused", "HOOK_SIGNATURES", "PLUGIN_CLASS", "PLUGIN_JAR", "build", "call_of", "source_text"]
